/// The rate simulated pressure changes at.
const RATE_OF_PRESSURE_CHANGE: f64 = 0.275;
/// π with a tiny offset, as the library has it (it avoids rendering artefacts in browsers).
const FIXED_PI: f64 = std::f64::consts::PI + 0.0001;
const START_CAP_SEGMENTS: f64 = 13.0;
const END_CAP_SEGMENTS: f64 = 29.0;
const CORNER_CAP_SEGMENTS: f64 = 13.0;
/// The end of a stroke within this distance of its last point is skipped, as noise.
const END_NOISE_THRESHOLD: f64 = 3.0;
const MIN_STREAMLINE_T: f64 = 0.15;
const STREAMLINE_T_RANGE: f64 = 0.85;
const MIN_RADIUS: f64 = 0.01;
const DEFAULT_FIRST_PRESSURE: f64 = 0.25;
const DEFAULT_PRESSURE: f64 = 0.5;
const UNIT_OFFSET: Vec2 = Vec2::new(1.0, 1.0);

/// An input point: where the pointer was, and its pressure (0 to 1) if it has one.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct InputPoint {
    pub x: f64,
    pub y: f64,
    pub pressure: Option<f64>,
}

impl InputPoint {
    pub fn new(x: f64, y: f64) -> Self {
        InputPoint {
            x,
            y,
            pressure: None,
        }
    }

    pub fn with_pressure(x: f64, y: f64, pressure: f64) -> Self {
        InputPoint {
            x,
            y,
            pressure: Some(pressure),
        }
    }

    fn xy(&self) -> Vec2 {
        Vec2::new(self.x, self.y)
    }
}

/// How far a stroke's start or end narrows to a point.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub enum Taper {
    /// No taper.
    #[default]
    None,
    /// Over the whole stroke (at least its size).
    Full,
    /// Over this distance.
    Distance(f64),
}

/// A stroke's start or end.
#[derive(Debug, Clone, Copy)]
pub struct StrokeEnd {
    /// A round cap (or a flat one), when not tapered.
    pub cap: bool,
    pub taper: Taper,
    /// The taper's easing, from 0 (the tip) to 1.
    pub easing: fn(f64) -> f64,
}

impl StrokeEnd {
    /// The start's defaults: a round cap, no taper, ease-out quadratic.
    pub const START: StrokeEnd = StrokeEnd {
        cap: true,
        taper: Taper::None,
        easing: |t| t * (2.0 - t),
    };

    /// The end's defaults: a round cap, no taper, ease-out cubic.
    pub const END: StrokeEnd = StrokeEnd {
        cap: true,
        taper: Taper::None,
        easing: |t| {
            let t = t - 1.0;
            t * t * t + 1.0
        },
    };
}

/// The options, with perfect-freehand's defaults.
#[derive(Debug, Clone, Copy)]
pub struct StrokeOptions {
    /// The stroke's base diameter.
    pub size: f64,
    /// How much pressure narrows the stroke, -1 to 1 (0: no effect).
    pub thinning: f64,
    /// How much to soften the outline's edges, 0 to 1.
    pub smoothing: f64,
    /// How much to smooth the input, 0 to 1.
    pub streamline: f64,
    /// The pressure's easing.
    pub easing: fn(f64) -> f64,
    /// Whether pressure comes from the pointer's speed rather than the input (for a mouse).
    pub simulate_pressure: bool,
    pub start: StrokeEnd,
    pub end: StrokeEnd,
    /// Whether the stroke is finished: its last point is then used as it is.
    pub last: bool,
}

impl Default for StrokeOptions {
    fn default() -> Self {
        StrokeOptions {
            size: 16.0,
            thinning: 0.5,
            smoothing: 0.5,
            streamline: 0.5,
            easing: |t| t,
            simulate_pressure: true,
            start: StrokeEnd::START,
            end: StrokeEnd::END,
            last: false,
        }
    }
}

/// A smoothed point of a stroke, from [`stroke_points`].
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct StrokePoint {
    pub point: Point,
    pub pressure: f64,
    /// From the previous point to here.
    pub distance: f64,
    /// The unit vector from here to the previous point.
    pub vector: Vec2,
    /// The stroke's length up to here.
    pub running_length: f64,
}

fn is_valid_pressure(pressure: Option<f64>) -> Option<f64> {
    // NaN fails `>= 0`, as in the library.
    pressure.filter(|p| *p >= 0.0)
}

fn lrp(a: Vec2, b: Vec2, t: f64) -> Vec2 {
    a + (b - a) * t
}

fn per(a: Vec2) -> Vec2 {
    Vec2::new(a.y, -a.x)
}

fn uni(a: Vec2) -> Vec2 {
    a / a.x.hypot(a.y)
}

fn dist(a: Vec2, b: Vec2) -> f64 {
    (a.y - b.y).hypot(a.x - b.x)
}

fn dist2(a: Vec2, b: Vec2) -> f64 {
    let dx = a.x - b.x;
    let dy = a.y - b.y;
    dx * dx + dy * dy
}

fn rot_around(a: Vec2, c: Vec2, r: f64) -> Vec2 {
    let (s, co) = r.sin_cos();
    let px = a.x - c.x;
    let py = a.y - c.y;
    Vec2::new(px * co - py * s + c.x, px * s + py * co + c.y)
}

fn prj(a: Vec2, b: Vec2, c: f64) -> Vec2 {
    a + b * c
}

fn stroke_radius(size: f64, thinning: f64, pressure: f64, easing: fn(f64) -> f64) -> f64 {
    size * easing(0.5 - thinning * (0.5 - pressure))
}

fn simulate_pressure(prev_pressure: f64, distance: f64, size: f64) -> f64 {
    let sp = (distance / size).min(1.0);
    let rp = (1.0 - sp).min(1.0);
    (prev_pressure + (rp - prev_pressure) * (sp * RATE_OF_PRESSURE_CHANGE)).min(1.0)
}

/// Smooths and measures the input: perfect-freehand's `getStrokePoints`.
pub fn stroke_points(input: &[InputPoint], options: &StrokeOptions) -> Vec<StrokePoint> {
    let StrokeOptions {
        streamline,
        size,
        last: is_complete,
        ..
    } = *options;
    if input.is_empty() {
        return Vec::new();
    }
    let t = MIN_STREAMLINE_T + (1.0 - streamline) * STREAMLINE_T_RANGE;

    let mut pts: Vec<(Vec2, Option<f64>)> = input.iter().map(|p| (p.xy(), p.pressure)).collect();
    // Two points: add three between them, to avoid "dash" lines with tapers. The library's
    // added points (the last one too) carry no pressure.
    if pts.len() == 2 {
        let first = pts[0].0;
        let last = pts[1].0;
        pts.truncate(1);
        for i in 1..5 {
            pts.push((lrp(first, last, f64::from(i) / 4.0), None));
        }
    }
    // One point: add another 1 px away.
    if pts.len() == 1 {
        pts.push((pts[0].0 + UNIT_OFFSET, pts[0].1));
    }

    let mut stroke = vec![StrokePoint {
        point: pts[0].0.to_point(),
        pressure: is_valid_pressure(pts[0].1).unwrap_or(DEFAULT_FIRST_PRESSURE),
        vector: UNIT_OFFSET,
        distance: 0.0,
        running_length: 0.0,
    }];
    let mut has_reached_minimum_length = false;
    let mut running_length = 0.0;
    let mut prev = stroke[0];
    let max = pts.len() - 1;

    for (i, &(input, pressure)) in pts.iter().enumerate().skip(1) {
        let point = if is_complete && i == max {
            input
        } else {
            lrp(prev.point.to_vec2(), input, t)
        };
        let prev_point = prev.point.to_vec2();
        if prev_point == point {
            continue;
        }
        let distance = dist(point, prev_point);
        running_length += distance;
        // At the start, wait until the stroke is its size long, to avoid noise.
        if i < max && !has_reached_minimum_length {
            if running_length < size {
                continue;
            }
            has_reached_minimum_length = true;
        }
        prev = StrokePoint {
            point: point.to_point(),
            pressure: is_valid_pressure(pressure).unwrap_or(DEFAULT_PRESSURE),
            vector: uni(prev_point - point),
            distance,
            running_length,
        };
        stroke.push(prev);
    }

    stroke[0].vector = stroke.get(1).map_or(Vec2::ZERO, |p| p.vector);
    stroke
}

fn taper_distance(taper: Taper, size: f64, total_length: f64) -> f64 {
    match taper {
        Taper::None => 0.0,
        Taper::Full => size.max(total_length),
        Taper::Distance(d) => d,
    }
}

/// Whether a number is "truthy" as JavaScript has it: neither 0 nor NaN.
fn truthy(n: f64) -> bool {
    n != 0.0 && !n.is_nan()
}

/// The outline of measured points: perfect-freehand's `getStrokeOutlinePoints`.
pub fn stroke_outline_points(points: &[StrokePoint], options: &StrokeOptions) -> Vec<Point> {
    let StrokeOptions {
        size,
        smoothing,
        thinning,
        simulate_pressure: should_simulate,
        easing,
        start,
        end,
        last: is_complete,
        ..
    } = *options;

    if points.is_empty() || size <= 0.0 {
        return Vec::new();
    }
    let n = points.len();
    let total_length = points[n - 1].running_length;
    let taper_start = taper_distance(start.taper, size, total_length);
    let taper_end = taper_distance(end.taper, size, total_length);
    // Math.pow(x, 2), which is x * x.
    let min_distance = (size * smoothing) * (size * smoothing);

    let mut left: Vec<Vec2> = Vec::new();
    let mut right: Vec<Vec2> = Vec::new();

    // The first pressures, averaged, so a stroke doesn't start fat.
    let mut prev_pressure = points.iter().take(10).fold(points[0].pressure, |acc, p| {
        let pressure = if should_simulate {
            simulate_pressure(acc, p.distance, size)
        } else {
            p.pressure
        };
        (acc + pressure) / 2.0
    });

    let mut radius = stroke_radius(size, thinning, points[n - 1].pressure, easing);
    let mut first_radius: Option<f64> = None;
    let mut prev_vector = points[0].vector;
    let mut prev_left = points[0].point.to_vec2();
    let mut prev_right = prev_left;
    let mut temp_left;
    let mut temp_right;
    let mut is_prev_point_sharp_corner = false;

    for i in 0..n {
        let StrokePoint {
            point,
            vector,
            distance,
            running_length,
            mut pressure,
        } = points[i];
        let point = point.to_vec2();
        let is_last_point = i == n - 1;

        // Skip noise at the end of the line.
        if !is_last_point && total_length - running_length < END_NOISE_THRESHOLD {
            continue;
        }

        if truthy(thinning) {
            if should_simulate {
                pressure = simulate_pressure(prev_pressure, distance, size);
            }
            radius = stroke_radius(size, thinning, pressure, easing);
        } else {
            radius = size / 2.0;
        }
        if first_radius.is_none() {
            first_radius = Some(radius);
        }

        let taper_start_strength = if running_length < taper_start {
            (start.easing)(running_length / taper_start)
        } else {
            1.0
        };
        let taper_end_strength = if total_length - running_length < taper_end {
            (end.easing)((total_length - running_length) / taper_end)
        } else {
            1.0
        };
        radius = MIN_RADIUS.max(radius * taper_start_strength.min(taper_end_strength));

        // A sharp corner (more than a right angle) gets a round cap of its own.
        let next_vector = if is_last_point {
            points[i].vector
        } else {
            points[i + 1].vector
        };
        let next_dpr = if is_last_point {
            1.0
        } else {
            vector.dot(next_vector)
        };
        let prev_dpr = vector.dot(prev_vector);
        let is_point_sharp_corner = prev_dpr < 0.0 && !is_prev_point_sharp_corner;
        let is_next_point_sharp_corner = next_dpr < 0.0;

        if is_point_sharp_corner || is_next_point_sharp_corner {
            let offset = per(prev_vector) * radius;
            let step = 1.0 / CORNER_CAP_SEGMENTS;
            let mut t = 0.0;
            temp_left = prev_left;
            temp_right = prev_right;
            while t <= 1.0 {
                temp_left = rot_around(point - offset, point, FIXED_PI * t);
                left.push(temp_left);
                temp_right = rot_around(point + offset, point, FIXED_PI * -t);
                right.push(temp_right);
                t += step;
            }
            prev_left = temp_left;
            prev_right = temp_right;
            if is_next_point_sharp_corner {
                is_prev_point_sharp_corner = true;
            }
            continue;
        }
        is_prev_point_sharp_corner = false;

        if is_last_point {
            let offset = per(vector) * radius;
            left.push(point - offset);
            right.push(point + offset);
            continue;
        }

        // Points either side, kept when far enough from the last kept one.
        let offset = per(lrp(next_vector, vector, next_dpr)) * radius;
        temp_left = point - offset;
        if i <= 1 || dist2(prev_left, temp_left) > min_distance {
            left.push(temp_left);
            prev_left = temp_left;
        }
        temp_right = point + offset;
        if i <= 1 || dist2(prev_right, temp_right) > min_distance {
            right.push(temp_right);
            prev_right = temp_right;
        }

        prev_pressure = pressure;
        prev_vector = vector;
    }

    // Caps. Tapered ends have none, but a very short stroke may be a dot.
    let first_point = points[0].point.to_vec2();
    let last_point = if n > 1 {
        points[n - 1].point.to_vec2()
    } else {
        points[0].point.to_vec2() + UNIT_OFFSET
    };
    let mut start_cap: Vec<Vec2> = Vec::new();
    let mut end_cap: Vec<Vec2> = Vec::new();

    if n == 1 {
        if !(truthy(taper_start) || truthy(taper_end)) || is_complete {
            // `firstRadius || radius`: a first radius of 0 counts as none.
            let dot_radius = first_radius.filter(|r| truthy(*r)).unwrap_or(radius);
            return draw_dot(first_point, dot_radius);
        }
    } else {
        if truthy(taper_start) || (truthy(taper_end) && n == 1) {
            // A tapered start: no cap.
        } else if start.cap {
            start_cap = draw_round_start_cap(first_point, right[0]);
        } else {
            start_cap = draw_flat_start_cap(first_point, left[0], right[0]);
        }

        let direction = per(-points[n - 1].vector);
        if truthy(taper_end) || (truthy(taper_start) && n == 1) {
            end_cap.push(last_point);
        } else if end.cap {
            end_cap = draw_round_end_cap(last_point, direction, radius);
        } else {
            end_cap = draw_flat_end_cap(last_point, direction, radius);
        }
    }

    // The left side, round the end cap, back along the right side, then the start cap.
    right.reverse();
    left.into_iter()
        .chain(end_cap)
        .chain(right)
        .chain(start_cap)
        .map(Vec2::to_point)
        .collect()
}

/// A stroke's outline from its input points: perfect-freehand's `getStroke`.
pub fn stroke_outline(input: &[InputPoint], options: &StrokeOptions) -> Vec<Point> {
    stroke_outline_points(&stroke_points(input, options), options)
}

fn draw_dot(center: Vec2, radius: f64) -> Vec<Point> {
    let offset_point = center + Vec2::new(1.0, 1.0);
    let start = prj(center, uni(per(center - offset_point)), -radius);
    let step = 1.0 / START_CAP_SEGMENTS;
    let mut dot = Vec::new();
    let mut t = step;
    while t <= 1.0 {
        dot.push(rot_around(start, center, FIXED_PI * 2.0 * t).to_point());
        t += step;
    }
    dot
}

fn draw_round_start_cap(center: Vec2, right_point: Vec2) -> Vec<Vec2> {
    let step = 1.0 / START_CAP_SEGMENTS;
    let mut cap = Vec::new();
    let mut t = step;
    while t <= 1.0 {
        cap.push(rot_around(right_point, center, FIXED_PI * t));
        t += step;
    }
    cap
}

fn draw_flat_start_cap(center: Vec2, left_point: Vec2, right_point: Vec2) -> Vec<Vec2> {
    let corners = left_point - right_point;
    let a = corners * 0.5;
    let b = corners * 0.51;
    vec![center - a, center - b, center + b, center + a]
}

fn draw_round_end_cap(center: Vec2, direction: Vec2, radius: f64) -> Vec<Vec2> {
    let start = prj(center, direction, radius);
    let step = 1.0 / END_CAP_SEGMENTS;
    let mut cap = Vec::new();
    let mut t = step;
    while t < 1.0 {
        cap.push(rot_around(start, center, FIXED_PI * 3.0 * t));
        t += step;
    }
    cap
}

fn draw_flat_end_cap(center: Vec2, direction: Vec2, radius: f64) -> Vec<Vec2> {
    vec![
        center + direction * radius,
        center + direction * (radius * 0.99),
        center - direction * (radius * 0.99),
        center - direction * radius,
    ]
}
