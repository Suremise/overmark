//! Pressure-sensitive freehand strokes: the outline of a stroke drawn through input points.
//!
//! A port of [perfect-freehand](https://github.com/steveruizok/perfect-freehand) 1.2.3 by Steve
//! Ruiz (MIT; its licence is in `third_party/ported/perfect-freehand.LICENSE` and
//! THIRD-PARTY-NOTICES.txt). It follows the TypeScript step for step, so its output matches the
//! library's: `fixtures.rs` holds outlines the library made, and the tests compare.
//!
//! - [`stroke_points`] smooths the input (streamline) and measures it: perfect-freehand's
//!   `getStrokePoints`.
//! - [`stroke_outline_points`] turns those into the outline's polygon, with pressure, thinning,
//!   tapers and caps: `getStrokeOutlinePoints`.
//! - [`stroke_outline`] does both: `getStroke`.
//!
//! The outline is a closed polygon, its points in order: fill it (non-zero) to draw the stroke.
//!
//! Differences from the library, none of which change its output:
//! - Input points are `[x, y, pressure]` with the pressure optional, as the library's array form
//!   (a missing pressure is 0.25 for the first point and 0.5 after). Its `{x, y, pressure}`
//!   object form, where a missing pressure is always 0.5, isn't ported: pass the 0.5.
//! - Easing functions are plain `fn(f64) -> f64`.
//! - A taper is [`Taper`] rather than `false | true | number`.

use kurbo::{Point, Vec2};

